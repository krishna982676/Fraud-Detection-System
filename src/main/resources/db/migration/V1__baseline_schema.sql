-- V1: Baseline Schema with organization_id support for all core engine tables

CREATE TABLE IF NOT EXISTS transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id VARCHAR(36) NOT NULL,
    transaction_id VARCHAR(64) NOT NULL,
    user_id VARCHAR(64) NOT NULL,
    amount DOUBLE PRECISION NOT NULL,
    merchant_category VARCHAR(32) NOT NULL,
    location VARCHAR(64) NOT NULL,
    device_type VARCHAR(32) NOT NULL,
    hour_of_day INT NOT NULL,
    distance_from_home DOUBLE PRECISION NOT NULL,
    txn_count_last_24h INT NOT NULL,
    is_international BOOLEAN NOT NULL,
    fraud_probability DOUBLE PRECISION NOT NULL,
    ml_score DOUBLE PRECISION,
    rule_score DOUBLE PRECISION,
    final_score DOUBLE PRECISION,
    is_fraud BOOLEAN NOT NULL,
    risk_level VARCHAR(16) NOT NULL,
    reasons VARCHAR(2000),
    structured_reasons_json VARCHAR(4000),
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_txn_org_txnid UNIQUE (organization_id, transaction_id)
);

CREATE INDEX IF NOT EXISTS idx_txn_org_id ON transactions (organization_id);
CREATE INDEX IF NOT EXISTS idx_txn_org_created ON transactions (organization_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_txn_org_user ON transactions (organization_id, user_id);

CREATE TABLE IF NOT EXISTS alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id VARCHAR(36) NOT NULL,
    transaction_id VARCHAR(64) NOT NULL,
    user_id VARCHAR(64) NOT NULL,
    amount DOUBLE PRECISION NOT NULL,
    merchant_category VARCHAR(32) NOT NULL,
    location VARCHAR(64) NOT NULL,
    fraud_probability DOUBLE PRECISION NOT NULL,
    risk_level VARCHAR(16) NOT NULL,
    reasons VARCHAR(2000),
    structured_reasons_json VARCHAR(4000),
    event_count INT NOT NULL DEFAULT 1,
    status VARCHAR(16) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    last_event_at TIMESTAMP,
    updated_at TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_alerts_org_id ON alerts (organization_id);
CREATE INDEX IF NOT EXISTS idx_alerts_org_status ON alerts (organization_id, status);
CREATE INDEX IF NOT EXISTS idx_alerts_org_created ON alerts (organization_id, created_at DESC);

CREATE TABLE IF NOT EXISTS analyst_feedback (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id VARCHAR(36) NOT NULL,
    alert_id BIGINT,
    transaction_id VARCHAR(64),
    user_id VARCHAR(64),
    amount DOUBLE PRECISION,
    merchant_category VARCHAR(32),
    location VARCHAR(64),
    device_type VARCHAR(32),
    hour_of_day INT,
    distance_from_home DOUBLE PRECISION,
    txn_count_last_24h INT,
    is_international BOOLEAN,
    is_actual_fraud BOOLEAN NOT NULL,
    notes VARCHAR(1000),
    created_at TIMESTAMP NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_feedback_org_id ON analyst_feedback (organization_id);

CREATE TABLE IF NOT EXISTS user_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id VARCHAR(36) NOT NULL,
    user_id VARCHAR(64) NOT NULL,
    sum_amount DOUBLE PRECISION DEFAULT 0.0,
    sum_sq_amount DOUBLE PRECISION DEFAULT 0.0,
    txn_count BIGINT DEFAULT 0,
    primary_city VARCHAR(64),
    primary_category VARCHAR(64),
    last_location VARCHAR(64),
    last_transaction_at TIMESTAMP,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_user_profiles_org_user UNIQUE (organization_id, user_id)
);

CREATE INDEX IF NOT EXISTS idx_profiles_org_id ON user_profiles (organization_id);

CREATE TABLE IF NOT EXISTS model_metrics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id VARCHAR(36) NOT NULL,
    algorithm VARCHAR(64) NOT NULL,
    trained_at TIMESTAMP NOT NULL,
    dataset_rows INT NOT NULL,
    accuracy DOUBLE PRECISION NOT NULL,
    precision_val DOUBLE PRECISION NOT NULL,
    recall_val DOUBLE PRECISION NOT NULL,
    f1_val DOUBLE PRECISION NOT NULL,
    roc_auc_val DOUBLE PRECISION NOT NULL,
    baseline_algorithm VARCHAR(64),
    baseline_accuracy DOUBLE PRECISION,
    baseline_precision DOUBLE PRECISION,
    baseline_recall DOUBLE PRECISION,
    baseline_f1 DOUBLE PRECISION,
    baseline_roc_auc DOUBLE PRECISION,
    logistic_algorithm VARCHAR(64),
    logistic_accuracy DOUBLE PRECISION,
    logistic_precision DOUBLE PRECISION,
    logistic_recall DOUBLE PRECISION,
    logistic_f1 DOUBLE PRECISION,
    logistic_roc_auc DOUBLE PRECISION,
    confusion_matrix TEXT,
    threshold_sweep_json TEXT,
    feature_importances_json TEXT
);

CREATE INDEX IF NOT EXISTS idx_metrics_org_id ON model_metrics (organization_id);

CREATE TABLE IF NOT EXISTS demo_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(100) NOT NULL,
    company VARCHAR(100),
    message VARCHAR(1000),
    created_at TIMESTAMP NOT NULL
);
